"""
Prediction adapter for the Ethiopian Smallholder Crop-Yield model.

Builds the model's 20 input features from plot-level inputs exactly as the training
pipeline does (src/features.py), looks up growing-season weather and market price
automatically, and returns yield and revenue.

All lookup tables in app/assets/ are generated by `python src/build_app_assets.py`
from the cleaned master tables, so app inputs match the training distribution.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

BASE_DIR = Path(__file__).resolve().parent
PROJECT_DIR = BASE_DIR.parent
ASSETS_DIR = BASE_DIR / "assets"

REGIONS = ["Oromia", "Amhara", "SNNPR", "Tigray", "Somali"]
CROPS = ["teff", "wheat", "maize", "sorghum", "barley"]
YEARS = [2021, 2022, 2023, 2024]
# Planting months present in the survey data (and therefore known to the model)
PLANTING_MONTHS = ["Feb", "Mar", "Jun", "Jul", "Aug"]
MEHER_MONTHS = ["Jun", "Jul", "Aug"]  # same definition as src/features.py

QUINTALS_PER_TON = 10.0


class ModelUnavailableError(RuntimeError):
    """Raised when the production model cannot be loaded."""


def normalize_region(region: str) -> str:
    r = str(region).strip()
    return "SNNPR" if r.upper() == "SNNPR" else r.title()


def normalize_crop(crop: str) -> str:
    return str(crop).strip().lower()


def normalize_month(month: str) -> str:
    return str(month).strip()[:3].title()


class CropYieldPredictor:
    def __init__(self) -> None:
        self.model = self._load_model()
        self.feature_names = list(self.model.feature_names_in_)
        self.weather = pd.read_csv(ASSETS_DIR / "weather_lookup.csv").set_index(
            ["region", "survey_year", "planting_month"]
        )
        self.rainfall = pd.read_csv(ASSETS_DIR / "rainfall_lookup.csv").set_index(
            ["region", "survey_year", "planting_month"]
        )["rainfall_mm_season"]
        self.prices = pd.read_csv(ASSETS_DIR / "price_lookup.csv").set_index(
            ["region", "crop_type", "year"]
        )["price_birr_per_quintal"]
        self.profiles = pd.read_csv(ASSETS_DIR / "plot_profiles.csv").set_index(
            ["region", "crop_type"]
        )
        metrics_path = ASSETS_DIR / "model_metrics.json"
        self.metrics = json.loads(metrics_path.read_text(encoding="utf-8")) if metrics_path.exists() else {}

    # ------------------------------------------------------------------ loading
    @staticmethod
    def _load_model():
        import joblib

        for p in (ASSETS_DIR / "final_model.joblib", PROJECT_DIR / "models" / "final_model.joblib"):
            if p.exists():
                return joblib.load(p)
        raise ModelUnavailableError(
            "final_model.joblib not found in app/assets/ or models/. "
            "Run notebooks/04_modeling_and_evaluation.ipynb or src/train.py."
        )

    @property
    def is_production(self) -> bool:
        return self.model is not None

    # ------------------------------------------------------------------ lookups
    def get_weather_context(self, region: str, year: int, planting_month: str) -> dict:
        """Growing-season weather (planting month + 3 following months) for this region/year."""
        key = (normalize_region(region), int(year), normalize_month(planting_month))
        if key not in self.weather.index:
            raise KeyError(f"No growing-season weather for {key}")
        row = self.weather.loc[key]
        return {
            "weather_season_mean_temp": float(row["weather_season_mean_temp"]),
            "weather_season_rainfall_mm": float(row["weather_season_rainfall_mm"]),
            "weather_season_heat_days": float(row["weather_season_heat_days"]),
            "weather_temp_anomaly_c": float(row["weather_temp_anomaly_c"]),
        }

    def get_typical_plot_rainfall(self, region: str, year: int, planting_month: str) -> float:
        """Median self-reported plot rainfall for surveyed plots in this region/year/month."""
        key = (normalize_region(region), int(year), normalize_month(planting_month))
        return float(self.rainfall.loc[key])

    def get_market_price(self, region: str, crop_type: str, year: int) -> float:
        """Cleaned market price (Birr/quintal). Used only for revenue, never as a model input."""
        return float(self.prices.loc[(normalize_region(region), normalize_crop(crop_type), int(year))])

    def get_profile(self, region: str, crop_type: str) -> dict:
        return self.profiles.loc[(normalize_region(region), normalize_crop(crop_type))].to_dict()

    # ------------------------------------------------------------------ features
    def build_features(self, df: pd.DataFrame, weather_overrides: dict | None = None) -> pd.DataFrame:
        """
        Converts raw plot inputs into the model's feature frame.
        Formulas mirror src/features.py::build_master_table exactly.
        `weather_overrides` lets the stress radar apply shocks, e.g.
        {"temp_delta": 2.0, "rain_mult": 0.65, "heat_days_add": 4}.
        """
        out = pd.DataFrame(index=df.index)
        out["region"] = df["region"].map(normalize_region)
        out["crop_type"] = df["crop_type"].map(normalize_crop)
        out["planting_month"] = df["planting_month"].map(normalize_month)
        years = df.get("survey_year", pd.Series(2024, index=df.index)).astype(int)

        bad_months = set(out["planting_month"]) - set(PLANTING_MONTHS)
        if bad_months:
            raise ValueError(f"Unsupported planting month(s) {sorted(bad_months)}; use {PLANTING_MONTHS}")

        w = pd.DataFrame(
            [self.get_weather_context(r, y, m) for r, y, m in zip(out["region"], years, out["planting_month"])],
            index=df.index,
        )

        if "rainfall_mm_season" in df and df["rainfall_mm_season"].notna().all():
            plot_rain = df["rainfall_mm_season"].astype(float)
        else:
            typical = pd.Series(
                [self.get_typical_plot_rainfall(r, y, m) for r, y, m in zip(out["region"], years, out["planting_month"])],
                index=df.index,
            )
            plot_rain = df["rainfall_mm_season"].astype(float).fillna(typical) if "rainfall_mm_season" in df else typical

        if weather_overrides:
            temp_delta = float(weather_overrides.get("temp_delta", 0.0))
            rain_mult = float(weather_overrides.get("rain_mult", 1.0))
            w["weather_season_mean_temp"] += temp_delta
            w["weather_temp_anomaly_c"] += temp_delta
            w["weather_season_rainfall_mm"] *= rain_mult
            w["weather_season_heat_days"] += float(weather_overrides.get("heat_days_add", 0.0))
            plot_rain = plot_rain * rain_mult

        out["altitude_m"] = df["altitude_m"].astype(float)
        out["rainfall_mm_season"] = plot_rain
        out["farm_size_ha"] = df["farm_size_ha"].astype(float)
        out["fertilizer_kg_per_ha"] = df["fertilizer_kg_per_ha"].astype(float)
        out["improved_seed_used"] = df["improved_seed_used"].astype(int)
        out["pest_disease_flag"] = df["pest_disease_flag"].astype(int)
        out["soil_quality_index"] = df["soil_quality_index"].astype(float)
        out["labor_days_per_ha"] = df["labor_days_per_ha"].astype(float)
        for c in w.columns:
            out[c] = w[c]

        # Engineered features: identical to src/features.py
        out["fertilizer_improved_seed_interaction"] = out["fertilizer_kg_per_ha"] * out["improved_seed_used"]
        out["weather_rain_discrepancy_ratio"] = out["rainfall_mm_season"] / (out["weather_season_rainfall_mm"] + 1e-5)
        out["labor_intensity_per_farm_size"] = out["labor_days_per_ha"] / (out["farm_size_ha"] + 0.1)
        out["is_meher_season"] = out["planting_month"].isin(MEHER_MONTHS).astype(int)
        out["altitude_temp_index"] = out["altitude_m"] / (out["weather_season_mean_temp"] + 273.15)

        return out[self.feature_names]

    # ------------------------------------------------------------------ predict
    def predict_batch(self, df: pd.DataFrame, weather_overrides: dict | None = None) -> pd.DataFrame:
        """Vectorised inference for one or many plots; adds yield, harvest and revenue columns."""
        df = df.reset_index(drop=True)
        X = self.build_features(df, weather_overrides)
        yields = np.clip(self.model.predict(X), 0.1, 9.0)  # same physical bounds as the submission

        res = df.copy()
        years = df.get("survey_year", pd.Series(2024, index=df.index)).astype(int)
        res["predicted_yield_t_ha"] = yields.round(3)
        res["total_harvest_tons"] = (yields * df["farm_size_ha"].astype(float)).round(3)
        res["total_quintals"] = (res["total_harvest_tons"] * QUINTALS_PER_TON).round(1)
        res["price_birr_per_quintal"] = [
            self.get_market_price(r, c, y) for r, c, y in zip(df["region"], df["crop_type"], years)
        ]
        res["gross_revenue_birr"] = (res["total_harvest_tons"] * QUINTALS_PER_TON * res["price_birr_per_quintal"]).round(0)
        for c in ("weather_season_mean_temp", "weather_season_rainfall_mm", "weather_season_heat_days",
                  "weather_temp_anomaly_c", "rainfall_mm_season"):
            res[f"model_{c}"] = X[c].values
        return res

    def predict(self, inputs: dict, weather_overrides: dict | None = None) -> dict:
        r = self.predict_batch(pd.DataFrame([inputs]), weather_overrides).iloc[0]
        return {
            "predicted_yield_tons_per_ha": float(r["predicted_yield_t_ha"]),
            "total_harvest_tons": float(r["total_harvest_tons"]),
            "total_quintals": float(r["total_quintals"]),
            "price_birr_per_quintal": float(r["price_birr_per_quintal"]),
            "gross_revenue_birr": float(r["gross_revenue_birr"]),
            "engine": "Production ML Pipeline (final_model.joblib)",
            "is_production": True,
            "weather_looked_up": {
                "season_mean_temp_c": float(r["model_weather_season_mean_temp"]),
                "season_rainfall_mm": float(r["model_weather_season_rainfall_mm"]),
                "season_heat_days": float(r["model_weather_season_heat_days"]),
                "temp_anomaly_c": float(r["model_weather_temp_anomaly_c"]),
                "plot_rainfall_mm": float(r["model_rainfall_mm_season"]),
            },
        }
